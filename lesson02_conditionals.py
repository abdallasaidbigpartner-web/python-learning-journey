"""
Lesson 2: Conditionals (if / elif / else)

Demonstrates branching logic using comparison and logical operators
to make decisions based on a variable value (grade calculation).
"""

score = 40
if score >= 90:
   print("Grade: A")
elif score >= 80 and score < 90:
     print("Geade: B")
elif score >= 70 and score < 80:
     print("Grade: C")
else:
     print("Grade: F")




